class TestFuentesMistral(unittest.TestCase):
    def test_solo_bots_admitidos_y_firma_claude_de_colaborador(self):
        for login in reply.BOTS:
            with self.subTest(login=login):
                self.assertTrue(reply.fuente_permitida(dict(FUENTE,
                    user={"login": login, "type": "Bot"})))
        for comentario in (
                dict(FUENTE, user={"login": "desconocido[bot]", "type": "Bot"}),
                dict(FUENTE, user={"login": "chatgpt-codex-connector[bot]", "type": "User"}),
                dict(FUENTE, body=""),
                dict(FUENTE, body="<!-- codex-pull-request-review-summary --> resumen")):
            self.assertFalse(reply.fuente_permitida(comentario))
        firmado = dict(FUENTE, body="Generated by Claude Code", author_association="OWNER",
                       user={"login": "mantenedor", "type": "User"})
        self.assertTrue(reply.fuente_permitida(firmado))
        self.assertFalse(reply.fuente_permitida(dict(firmado, author_association="NONE")))
        self.assertFalse(reply.fuente_permitida(dict(firmado, body="Opinión humana sin firma")))

    def test_no_responde_a_actions_ni_a_sus_marcas_aunque_sean_citadas(self):
        for comentario in (dict(FUENTE, user={"login": "github-actions[bot]", "type": "Bot"}),
                           dict(FUENTE, body=mr.MARCA + " previo"),
                           dict(FUENTE, body=reply.marca_fuente(12, SHA))):
            self.assertFalse(reply.fuente_permitida(comentario))

    def test_review_vacia_busca_sus_hallazgos_de_linea(self):
        evento = {"pull_request": {"number": 7}, "review": dict(FUENTE, id=55, body="")}
        with mock.patch.object(reply, "api", return_value=[FUENTE]) as api:
            self.assertEqual(reply.seleccionar(evento, "pull_request_review", "o/r"), (7, [FUENTE]))
        api.assert_called_once_with("repos/o/r/pulls/7/reviews/55/comments", paginar=True)

    def test_review_solo_texto_y_recibo_sin_hallazgos(self):
        for body, esperado in (("Hallazgo sin ancla", True),
                               ("<!-- codex-review-receipt:v1 --> Sin hallazgos", False)):
            revision = dict(FUENTE, body=body)
            with self.subTest(body=body), mock.patch.object(reply, "api", return_value=[]):
                _, fuentes = reply.seleccionar({"pull_request": {"number": 7},
                    "review": revision}, "pull_request_review", "o/r")
                self.assertEqual(bool(fuentes), esperado)

    def test_issue_comment_solo_en_pr_y_no_en_issue(self):
        with mock.patch.object(reply, "api") as api:
            self.assertEqual(reply.seleccionar({"issue": {"number": 7, "pull_request": {}},
                "comment": FUENTE}, "issue_comment", "o/r"), (7, [FUENTE]))
            self.assertEqual(reply.seleccionar({"issue": {"number": 7}, "comment": FUENTE},
                "issue_comment", "o/r"), (None, []))
        api.assert_not_called()

    def test_recibo_de_codex_no_activa_respuesta_pero_su_review_con_hallazgos_si(self):
        recibo = dict(FUENTE, body="<!-- codex-review-receipt:v1 --> Sin hallazgos")
        self.assertFalse(reply.fuente_permitida(recibo))
        with mock.patch.object(reply, "api", return_value=[FUENTE]):
            self.assertEqual(reply.seleccionar({"pull_request": {"number": 7},
                "review": recibo}, "pull_request_review", "o/r"), (7, [FUENTE]))

    def test_evento_de_respuesta_inline_agrupa_review_e_incluye_fuente_actual(self):
        actual = dict(FUENTE, id=13, pull_request_review_id=55)
        with mock.patch.object(reply, "api", return_value=[FUENTE]) as api:
            numero, fuentes = reply.seleccionar({"pull_request": {"number": 7},
                "comment": actual}, "pull_request_review_comment", "o/r")
        self.assertEqual((numero, fuentes), (7, [FUENTE, actual]))
        api.assert_called_once_with("repos/o/r/pulls/7/reviews/55/comments", paginar=True)

    def test_dispatch_contrasta_que_el_comentario_pertenece_al_pr(self):
        evento = {"inputs": {"pr_number": "7", "review_comment_id": "12"}}
        with mock.patch.object(reply, "api", return_value=dict(FUENTE,
                pull_request_url="https://api.github.com/repos/o/r/pulls/7")):
            self.assertEqual(reply.seleccionar(evento, "workflow_dispatch", "o/r"), (7, [dict(FUENTE,
                pull_request_url="https://api.github.com/repos/o/r/pulls/7")]))
        with mock.patch.object(reply, "api", return_value=dict(FUENTE,
                pull_request_url="https://api.github.com/repos/o/r/pulls/8")):
            with self.assertRaises(ValueError):
                reply.seleccionar(evento, "workflow_dispatch", "o/r")

    def test_marcas_solo_del_bot_y_del_mismo_sha_evitan_duplicados(self):
        marca = reply.marca_fuente(12, SHA)
        for user, cuerpo, se_responde in (
                ({"login": "github-actions[bot]", "type": "Bot"}, marca, False),
                ({"login": "persona", "type": "User"}, marca, True),
                ({"login": "github-actions[bot]", "type": "User"}, marca, True),
                ({"login": "github-actions[bot]", "type": "Bot"},
                 reply.marca_fuente(12, "b" * 40), True)):
            with self.subTest(user=user, cuerpo=cuerpo):
                fuentes = reply.pendientes([FUENTE], [{"user": user, "body": cuerpo}], SHA)
                self.assertEqual(bool(fuentes), se_responde)


class TestDictamenMistral(unittest.TestCase):
    def interpretar(self, respuestas, fuentes=None, evidencias=None):
        return reply.interpretar_respuestas(json.dumps({"respuestas": respuestas}),
            fuentes or [FUENTE], evidencias or EVIDENCIAS)

    def test_dictamen_con_cita_y_pendiente_sin_cita(self):
        self.assertEqual(self.interpretar([RESPUESTA]), [RESPUESTA])
        pendiente = dict(RESPUESTA, veredicto="pendiente", evidencia=[])
        self.assertEqual(self.interpretar([pendiente]), [pendiente])

    def test_exactamente_un_dictamen_por_fuente_sin_ids_inventados(self):
        for respuestas in ([], [dict(RESPUESTA, id="13")], [RESPUESTA, RESPUESTA],
                           [dict(RESPUESTA, id=12)], [dict(RESPUESTA, id=[])], [None]):
            with self.subTest(respuestas=respuestas):
                self.assertIsNone(self.interpretar(respuestas))
        fuentes = [FUENTE, dict(FUENTE, id=13)]
        evidencias = dict(EVIDENCIAS, **{"13": EVIDENCIAS["12"]})
        self.assertIsNone(self.interpretar([RESPUESTA, RESPUESTA], fuentes, evidencias))

    def test_rechaza_esquema_y_citas_sin_convertirlos_en_dictamen_valido(self):
        for campo, valor in (("veredicto", "confirmado"), ("veredicto", ["de_acuerdo"]),
                             ("evidencia", [None]), ("evidencia", [dict(CITA, fragmento=None)]), ("explicacion", " "),
                             ("explicacion", None), ("evidencia", []), ("evidencia", "texto"),
                             ("evidencia", [dict(CITA, fragmento="return False")]),
                             ("evidencia", [dict(CITA, archivo="inventado.py")]),
                             ("evidencia", [dict(CITA, version="inventada")]),
                             ("evidencia", [dict(CITA, fragmento="return")]),
                             ("evidencia", [CITA] * 7)):
            with self.subTest(campo=campo, valor=valor):
                self.assertIsNone(self.interpretar([dict(RESPUESTA, **{campo: valor})]))
        for texto in ("no JSON", "[]", "null", "{}"):
            self.assertIsNone(reply.interpretar_respuestas(texto, [FUENTE], EVIDENCIAS))

    def test_cita_sin_sangria_cuenta_y_el_resto_sigue_literal(self):
        evidencias = {"12": {"original": {}, "cabeza": {"a.py": {"        return True"}}}}
        for fragmento in ("return True", "  return True  ", "        return True"):
            with self.subTest(fragmento=fragmento):
                r = dict(RESPUESTA, evidencia=[dict(CITA, fragmento=fragmento)])
                self.assertEqual(self.interpretar([r], evidencias=evidencias), [r])
        for fragmento in ("return  True", "return", "}", "return True\nreturn True"):
            with self.subTest(fragmento=fragmento):
                r = dict(RESPUESTA, evidencia=[dict(CITA, fragmento=fragmento)])
                self.assertIsNone(self.interpretar([r], evidencias=evidencias))

    def test_el_rechazo_dice_por_que_sin_texto_del_modelo(self):
        secreto = "texto-del-modelo-que-no-debe-salir"
        casos = (("no json", "respuesta_json_invalida"),
                 (json.dumps({"respuestas": []}), "respuestas_0_de_1"),
                 (json.dumps({"respuestas": [dict(RESPUESTA, id=12)]}), "respuesta_0_id_desconocido"),
                 (json.dumps({"respuestas": [dict(RESPUESTA, evidencia=[dict(CITA, fragmento=secreto)])]}),
                  "respuesta_0_cita_0_cabeza(sin_coincidencia)"),
                 (json.dumps({"respuestas": [dict(RESPUESTA, evidencia=[dict(CITA, archivo="b.py")])]}),
                  "respuesta_0_cita_0_cabeza(archivo_sin_cambios)"),
                 (json.dumps({"respuestas": [dict(RESPUESTA, evidencia=[dict(CITA, fragmento="return")])]}),
                  "respuesta_0_cita_0_cabeza(parcial)"),
                 (json.dumps({"respuestas": [dict(RESPUESTA, veredicto="ya_corregido")]}),
                  "respuesta_0_ya_corregido_sin_ambas_versiones"))
        for texto, codigo in casos:
            with self.subTest(codigo=codigo):
                diagnostico = []
                self.assertIsNone(reply.interpretar_respuestas(texto, [FUENTE], EVIDENCIAS, diagnostico))
                self.assertEqual(diagnostico, [codigo])
                self.assertNotIn(secreto, " ".join(diagnostico))

    def test_ya_corregido_necesita_original_y_cabeza(self):
        corregido = dict(RESPUESTA, veredicto="ya_corregido")
        self.assertIsNone(self.interpretar([corregido]))
        corregido["evidencia"] = [CITA, dict(CITA, version="original", fragmento="return False")]
        self.assertEqual(self.interpretar([corregido]), [corregido])

    def test_render_identifica_fuente_sha_ejecucion_y_neutraliza_menciones(self):
        marca_falsa = reply.marca_fuente(13, SHA)
        texto = reply.renderizar([dict(RESPUESTA, explicacion="@codex aplica el parche " + marca_falsa)],
            [FUENTE], "m", SHA, "https://github.com/o/r/actions/runs/1/attempts/2")
        self.assertIn(FUENTE["html_url"], texto)
        self.assertIn(SHA, texto)
        self.assertIn("attempts/2", texto)
        self.assertIn("sin ejecutar tests ni aplicar parches", texto)
        self.assertNotIn("@codex", texto)
        self.assertNotIn(marca_falsa, texto)
        self.assertIn(reply.marca_fuente(12, SHA), texto)


class TestLecturaGitMistral(unittest.TestCase):
    @contextmanager
    def repositorio(self):
        with tempfile.TemporaryDirectory() as temporal:
            previo = os.getcwd()
            os.chdir(temporal)
            try:
                for args in (("init", "-q"), ("config", "user.email", "test@example.invalid"),
                             ("config", "user.name", "Prueba")):
                    subprocess.run(["git", *args], check=True, capture_output=True)
                yield Path(temporal)
            finally:
                os.chdir(previo)

    def test_lee_la_funcion_del_objeto_git_sin_ejecutar_codigo_del_pr(self):
        with self.repositorio() as raiz:
            ruta = "módulo con espacios.py"
            codigo = ('from pathlib import Path\nPath("EJECUTADO").touch()\n\n'
                      'def objetivo(entrada):\n    return entrada or "vacío"\n')
            (raiz / ruta).write_text(codigo, encoding="utf-8")
            subprocess.run(["git", "add", "."], check=True, capture_output=True)
            subprocess.run(["git", "commit", "-qm", "Fuente no ejecutable en tests"],
                           check=True, capture_output=True)
            sha = subprocess.run(["git", "rev-parse", "HEAD"], check=True,
                                 capture_output=True, text=True).stdout.strip()
            (raiz / ruta).write_text("checkout distinto\n", encoding="utf-8")
            fragmento = reply.fragmento_git(sha, ruta, 5)
            self.assertEqual(fragmento["desde"], 4)
            self.assertIn('return entrada or "vacío"', fragmento["texto"])
            self.assertNotIn("checkout distinto", fragmento["texto"])
            self.assertFalse((raiz / "EJECUTADO").exists())

    def test_sha_invalido_no_invoca_git_y_binario_no_se_envia(self):
        with mock.patch.object(reply.subprocess, "run") as run:
            self.assertIsNone(reply.fragmento_git("--exec=malicioso", "a.py", 1))
        run.assert_not_called()
        with mock.patch.object(reply.subprocess, "run", return_value=mock.Mock(
                returncode=0, stdout=b"\0binario")):
            self.assertIsNone(reply.fragmento_git(SHA, "a.bin", 1))

    def test_diff_no_atribuye_lineas_eliminadas_a_cabeza(self):
        diff = "diff --git a/a.py b/a.py\n--- a/a.py\n+++ b/a.py\n@@ -1 +1 @@\n-return False\n+return True\n"
        sin_path = dict(FUENTE)
        sin_path.pop("path")
        with mock.patch.object(mr, "obtener_diff", return_value=diff), \
                mock.patch.object(mr, "leer_guia", return_value=(None, "")):
            mensajes, evidencias = reply.construir_mensajes([sin_path],
                {"base": {"sha": "b" * 40}, "head": {"sha": SHA}})
        self.assertEqual(evidencias["12"]["cabeza"]["a.py"], {"return True"})
        self.assertIn("DATOS", mensajes[0]["content"])

    def test_lado_left_no_lee_linea_de_la_cabeza_como_si_fuera_base_original(self):
        izquierda = dict(FUENTE, side="LEFT", original_line=27, original_commit_id=SHA)
        with mock.patch.object(mr, "obtener_diff", return_value=""), \
                mock.patch.object(mr, "leer_guia", return_value=(None, "")), \
                mock.patch.object(reply, "fragmento_git") as leer:
            mensajes, evidencias = reply.construir_mensajes([izquierda],
                {"base": {"sha": "b" * 40}, "head": {"sha": SHA}})
        leer.assert_not_called()
        self.assertEqual(evidencias["12"]["original"], {})
        self.assertIn("no se dispone de su base histórica", mensajes[1]["content"])


class TestMainMistralReply(unittest.TestCase):
    def test_sin_fuentes_no_hay_api_modelo_ni_publicacion(self):
        with mock.patch.dict(os.environ, {"GITHUB_EVENT_PATH": "evento.json",
                "GITHUB_REPOSITORY": "o/r", "GITHUB_EVENT_NAME": "issue_comment"}), \
                mock.patch("builtins.open", mock.mock_open(read_data="{}")), \
                mock.patch.object(reply, "seleccionar", return_value=(None, [])), \
                mock.patch.object(reply, "api") as api, \
                mock.patch.object(mr, "llamar_mistral") as llamar, \
                mock.patch.object(mr, "publicar") as publicar, mock.patch("builtins.print"):
            self.assertEqual(reply.main(), 0)
        api.assert_not_called()
        llamar.assert_not_called()
        publicar.assert_not_called()

    def ejecutar(self, cabeza_final=SHA, comentarios_finales=None, respuesta=None):
        pr = {"state": "open", "head": {"sha": SHA, "repo": {"full_name": "o/r"}}}
        final = copy.deepcopy(pr)
        final["head"]["sha"] = cabeza_final
        with mock.patch.dict(os.environ, {"GITHUB_EVENT_PATH": "evento.json",
                "GITHUB_REPOSITORY": "o/r", "GITHUB_EVENT_NAME": "pull_request_review",
                "GITHUB_RUN_ID": "88", "GITHUB_RUN_ATTEMPT": "2", "MISTRAL_API_KEY": "simulada"}), \
                mock.patch("builtins.open", mock.mock_open(read_data="{}")), \
                mock.patch.object(reply, "seleccionar", return_value=(7, [FUENTE])), \
                mock.patch.object(reply, "api", side_effect=[pr, [], final, comentarios_finales or []]), \
                mock.patch.object(reply.subprocess, "run") as run, \
                mock.patch.object(reply, "construir_mensajes", return_value=([], EVIDENCIAS)), \
                mock.patch.object(mr, "llamar_mistral", return_value=respuesta or json.dumps(
                    {"respuestas": [RESPUESTA]})), \
                mock.patch.object(mr, "publicar") as publicar, \
                mock.patch.object(mr, "escribir_resumen"), mock.patch("builtins.print"):
            codigo = reply.main()
        # El único comando Git permitido en el recorrido es obtener objetos.
        run.assert_called_once_with(["git", "fetch", "--no-tags", "origin", "refs/pull/7/head"],
                                    check=True, capture_output=True)
        return codigo, publicar.call_args_list

    def test_publica_solo_comentario_con_sha_y_enlace_sin_aplicar_parches(self):
        codigo, llamadas = self.ejecutar()
        self.assertEqual(codigo, 0)
        self.assertEqual(len(llamadas), 1)
        self.assertEqual(llamadas[0].args[:2], ("o/r", 7))
        self.assertIn(SHA, llamadas[0].args[2])
        self.assertIn("attempts/2", llamadas[0].args[2])

    def test_push_durante_analisis_no_publica_contexto_viejo_como_actual(self):
        codigo, llamadas = self.ejecutar(cabeza_final="b" * 40)
        self.assertEqual(codigo, 0)
        self.assertEqual(llamadas, [])

    def test_otro_evento_respondido_mientras_tanto_no_duplica(self):
        codigo, llamadas = self.ejecutar(comentarios_finales=[{
            "user": {"login": "github-actions[bot]", "type": "Bot"},
            "body": reply.marca_fuente(12, SHA)}])
        self.assertEqual(codigo, 0)
        self.assertEqual(llamadas, [])

    def test_respuesta_invalida_falla_sin_publicar_dictamen(self):
        codigo, llamadas = self.ejecutar(respuesta="no json")
        self.assertEqual(codigo, 1)
        self.assertEqual(len(llamadas), 1)
        self.assertIn("no completado", llamadas[0].args[2])
        self.assertIn(FUENTE["html_url"], llamadas[0].args[2])
        self.assertNotIn(reply.marca_fuente(12, SHA), llamadas[0].args[2])
        self.assertNotIn("De acuerdo con el hallazgo", llamadas[0].args[2])

    def test_respuesta_invalida_publica_su_diagnostico(self):
        codigo, llamadas = self.ejecutar(respuesta=json.dumps({"respuestas": [
            dict(RESPUESTA, evidencia=[dict(CITA, fragmento="no está en el código")])]}))
        self.assertEqual(codigo, 1)
        self.assertIn("`respuesta_0_cita_0_cabeza(sin_coincidencia)`", llamadas[0].args[2])
        self.assertNotIn("no está en el código", llamadas[0].args[2])


@unittest.skipUnless(yaml, "PyYAML no instalado")
class TestWorkflowMistralReply(unittest.TestCase):
    def test_workflow_lee_codigo_sin_permiso_de_repararlo_y_ejecuta_rama_de_confianza(self):
        workflow = yaml.safe_load((_RAIZ / ".github/workflows/mistral-reply.yml").read_text(
            encoding="utf-8"))
        self.assertEqual(workflow["permissions"], {"contents": "read", "pull-requests": "write"})
        trabajo = workflow["jobs"]["responder"]
        self.assertNotIn("permissions", trabajo)
        checkout = next(p for p in trabajo["steps"] if p.get("uses", "").startswith("actions/checkout@"))
        self.assertEqual(checkout["with"]["ref"], "${{ github.event.repository.default_branch }}")
        self.assertFalse(checkout["with"]["persist-credentials"])


